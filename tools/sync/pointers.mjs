// The skill pointers `sync` writes into every agent host's skill folder (.claude/skills/,
// .qwen/skills/): a folder named like the skill with a SKILL.md that carries the skill's `name` and
// `description` — all a host reads before deciding whether a question belongs to the skill — the
// marker below, and a link to the source SKILL.md. oikos's own pointers lead into `oikos/`; those of
// a mount (docs/design/mounts.md § What `sync` writes per mount, item 4) lead into the mount and
// say where the skill comes from.
import { existsSync, readFileSync, realpathSync } from 'node:fs';
import { join, relative } from 'node:path';
import { isRepoTop } from '../common/paths.mjs';
import { mountSkills } from '../common/mount-skills.mjs';

/** The line that marks a pointer sync wrote, so sync may replace or remove it and nothing else. */
export const MARKER = '<!-- oikos: generated by oikos/tools/sync/cli.mjs; do not edit this file by hand. -->';

/** Whether the file `file` is a pointer sync wrote (this marker, or the one an older sync wrote). */
export const isOurs = (file) => existsSync(file) && /oikos: generated by|Generated by tools\/sync\/cli\.mjs/.test(readFileSync(file, 'utf8'));

/**
 * The text of a skill pointer: the frontmatter of `fm` (`name`, `description`), the marker and the
 * `link` to the source SKILL.md; `origin` (for a mount's skill) is the paragraph that says where the
 * skill comes from.
 * @param {{name: string, description: string}} fm
 * @param {string} link
 * @param {string|null} origin
 * @returns {string}
 */
export const pointer = (fm, link, origin = null) => `---
name: ${fm.name}
description: ${fm.description}
---

# ${fm.name}

${MARKER}

Source skill: [${link}](${link})

${origin ? `${origin}\n\n` : ''}Read and follow the source SKILL.md. Do not duplicate its contents here.
`;

/** The paragraph of a mount's pointer: the mount as declared and its layer, that its rules are not loaded, where its files are changed. */
const originOf = (m, skill) => `Origin: the skill \`${skill.dir}\` of the mount \`${m.path}\` (${m.layer} layer), a repository this installation `
  + 'uses as a source, not part of oikos. The mount\'s own rules (its CLAUDE.md, its imports, its .claude/rules) are not loaded in this session. '
  + 'Work that writes into the mount, or needs its guards, is done in a session opened in the mount.';

/**
 * A mount's pointer is kept out of the installation's commits when the path it names is this machine's:
 * an outside mount's, or a local-layer one's — unless the person asked to commit it (`skills.commit`,
 * allowed only for an inside mount, whose link is relative).
 */
const keptOut = (m) => !m.inside || (m.layer === 'local' && !m.skills.commit);

const layerFile = (m) => (m.layer === 'local' ? '.local/mounts.yaml' : 'oikos.yaml');

/**
 * What a pointer of a mount's skill is: the mount, the skill (tools/common/mount-skills.mjs), whether
 * it stays out of the installation's commits, and its text for a host folder (`hostDir`, '.claude'):
 * the link is relative for an inside mount, so a committed pointer holds no absolute path, and the
 * skill's real path for an outside mount.
 * @typedef {object} MountPointer
 * @property {string} name `<prefix>-<skill folder>`
 * @property {object} mount
 * @property {{dir: string, file: string, description: string}} skill
 * @property {boolean} ignored kept out of the installation's commits
 * @property {(hostDir: string) => string} text
 */

/**
 * The pointers of every mount used for skills whose repository is there, and the problems found: a
 * name that an oikos pointer (`taken`) or an earlier mount's pointer has already is reported, and
 * that pointer is left out, so it never overwrites the other.
 * @param {string} install the installation's root
 * @param {object[]} mounts the resolved mounts
 * @param {string[]} taken the names of oikos's own pointers
 * @returns {{pointers: MountPointer[], problems: string[]}}
 */
export function mountPointers(install, mounts, taken) {
  const base = realpathSync(install);
  const pointers = [];
  const problems = [];
  for (const m of mounts.filter((mount) => mount.skills && isRepoTop(mount.root))) {
    for (const skill of mountSkills(m)) {
      const earlier = pointers.find((p) => p.name === skill.name);
      const clash = taken.includes(skill.name) ? 'a skill or agent of oikos' : earlier && `a skill of the mount ${earlier.mount.path}`;
      if (clash) {
        problems.push(`${layerFile(m)}: mounts.${m.path}: the pointer '${skill.name}' is also the name of ${clash} — set skills.prefix or skills.only`);
        continue;
      }
      const text = (hostDir) => {
        const link = m.inside ? relative(join(base, hostDir, 'skills', skill.name), skill.file) : skill.file;
        return pointer({ name: skill.name, description: JSON.stringify(skill.description) }, link, originOf(m, skill));
      };
      pointers.push({ name: skill.name, mount: m, skill, ignored: keptOut(m), text });
    }
  }
  return { pointers, problems };
}
