test('landscape lists the mounts and the origin of each mount skill, and setup status lists the mounts', () => {
  const { dir, ext } = world();
  assert.equal(sync(dir).status, 0);
  const mounts = tool(dir, 'landscape', ['mounts'], ENV);
  assert.equal(mounts.status, 0, mounts.output);
  assert.match(mounts.stdout, /^projects\/dev-root — shared layer, inside the installation · use: skills\n {2}skills: dev-deploy-status$/m);
  assert.match(mounts.stdout, /^vaults\/team — shared layer, inside the installation · use: wiki · wiki 'team'$/m);
  assert.match(mounts.stdout, /^vaults\/mine — local layer, inside the installation · use: skills$/m);
  assert.match(mounts.stdout, new RegExp(`^${ext.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')} — local layer, outside the installation · use: skills$`, 'm'));
  const json = JSON.parse(tool(dir, 'landscape', ['mounts', '--json'], ENV).stdout);
  assert.deepEqual(json.map((m) => [m.path, m.layer, m.inside]).slice(0, 2), [['projects/dev-root', 'shared', true], ['tools/Ops_Kit', 'shared', true]]);
  assert.deepEqual(json[0].skills.map((s) => s.name), ['dev-deploy-status']);

  const skills = tool(dir, 'landscape', ['skills'], ENV);
  assert.equal(skills.status, 0, skills.output);
  assert.match(skills.stdout, /^dev-deploy-status — Use deploy-status: a skill of the mount\n {2}origin: the skill deploy-status of the mount projects\/dev-root \(shared layer, inside the installation\)$/m);
  assert.match(skills.stdout, /^ext-report — .*\n {2}origin: .* \(local layer, outside the installation\)$/m);
  assert.match(skills.stdout, /^## engineering — /m, 'oikos\'s own skills are still listed');
  const one = tool(dir, 'landscape', ['skills', 'ops-kit-rollout'], ENV);
  assert.equal(one.status, 0, one.output);
  assert.match(one.stdout, /ops-kit-rollout/);
  assert.doesNotMatch(one.stdout, /dev-deploy-status/);
  const unknown = tool(dir, 'landscape', ['skills', 'nope'], ENV);
  assert.equal(unknown.status, 1);
  assert.match(unknown.output, /unknown skill: nope/);

  const status = tool(dir, 'setup', ['status', '--offline'], ENV);
  assert.match(status.stdout, /ok {2}mount projects\/dev-root — shared layer, inside the installation · use: skills/);
  assert.match(status.stdout, /ok {2}mount vaults\/team — shared layer, inside the installation · use: wiki · wiki 'team'/);
  assert.match(status.stdout, new RegExp(`ok {2}mount ${ext.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')} — local layer, outside the installation`));
});

