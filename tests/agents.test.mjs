// Standing agents (ADR 0006 D01, npm test): the charter checks of landscape.mjs on charters in a
// temporary folder, `agents:` and `desk:` of an installation's oikos.yaml, the pointer sync writes
// for a listed agent, the roster the session-start hook prints, the desk line of the context-pressure
// advice, and what handoff does about the desk's folder. Nothing here reaches the network.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';
import { CORE, cleanEnv, installation, tempDir, tool } from './helpers/installation.mjs';
import { loadAgents } from '../tools/common/landscape.mjs';

const HOOK = join(CORE, 'tools', 'hooks', 'host-hook.mjs');
const SECTIONS = ['Mission', 'Skills and how it uses them', 'Owns', 'Never', 'Session start', 'Closing a topic', 'Workers'];

/** A charter's text: frontmatter lines `fm` (a string) and the sections `sections`. */
const charter = (fm, sections = SECTIONS) => `---\n${fm}\n---\n\n# x\n\n${sections.map((s) => `## ${s}\n\ntext\n`).join('\n')}`;
const GOOD = 'name: tidy\ndescription: Tidies. Start it for "tidy".\nskills: [notes]\nowns: tidy\nmetadata:\n  owner: oikos';

/** The problems of the charters in `files` ({ folder: text }), judged against the skills in `skillDirs`. */
function problemsOf(files, skillDirs = ['notes', 'wiki']) {
  const root = tempDir('agents-');
  for (const [folder, text] of Object.entries(files)) {
    mkdirSync(join(root, folder), { recursive: true });
    if (text !== null) writeFileSync(join(root, folder, 'README.md'), text);
  }
  return loadAgents(skillDirs, root);
}

test('a valid charter loads, with its skills as a list and the folder as its name', () => {
  const { agents, problems } = problemsOf({ tidy: charter(GOOD) });
  assert.deepEqual(problems, []);
  assert.deepEqual(agents.map((a) => [a.dir, a.skills, a.owns, a.enabled]), [['tidy', ['notes'], 'tidy', false]]);
});

test('a charter is checked: frontmatter, name, skills, owns, sections, a name shared with a skill', () => {
  const found = (files, skills) => problemsOf(files, skills).problems.join('\n');
  assert.match(found({ tidy: null }), /agents\/tidy: no README\.md/);
  assert.match(found({ tidy: '# no frontmatter\n' }), /no frontmatter/);
  assert.match(found({ tidy: charter('name: tidy\nowns: tidy') }), /missing 'description'[\s\S]*missing 'skills'[\s\S]*missing 'metadata\.owner'/);
  assert.match(found({ tidy: charter(GOOD.replace('name: tidy', 'name: other')) }), /name 'other' differs from the folder/);
  assert.match(found({ tidy: charter(GOOD.replace('[notes]', '[notes, ghost]')) }), /skill 'ghost' does not exist in skills\//);
  for (const owns of ['.secrets', 'browser', 'Google', 'a/b', '..']) {
    assert.match(found({ tidy: charter(GOOD.replace('owns: tidy', `owns: ${owns}`)) }), /owns '.*' must be one open folder name/, owns);
  }
  assert.match(found({ tidy: charter(GOOD, SECTIONS.filter((s) => s !== 'Never' && s !== 'Workers')) }), /missing the section '## Never'[\s\S]*missing the section '## Workers'/);
  assert.match(found({ notes: charter(GOOD.replace('name: tidy', 'name: notes')) }, ['notes']), /the name is also a skill's/);
});

test('the desk charter of the core passes its own checks, and its skills exist', () => {
  const { agents, problems } = loadAgents();
  assert.deepEqual(problems, []);
  const desk = agents.find((a) => a.dir === 'desk');
  assert.ok(desk, 'agents/desk/README.md');
  assert.equal(desk.owns, 'desk');
  assert.deepEqual(desk.skills, ['notes', 'task-tracking', 'messaging', 'wiki', 'code-hosting']);
});

test('sync delivers a listed agent as a pointer in both hosts, and takes it back when it is unlisted', () => {
  const dir = installation((t) => t); // the fixture lists `agents: [desk]`
  assert.equal(tool(dir, 'sync', []).status, 0);
  for (const host of ['.claude', '.qwen']) {
    const file = join(dir, host, 'skills', 'desk', 'SKILL.md');
    const text = readFileSync(file, 'utf8');
    assert.match(text, /^---\nname: desk\ndescription: The standing desk/);
    assert.match(text, /oikos: generated by/);
    assert.match(text, /\.\.\/\.\.\/\.\.\/oikos\/agents\/desk\/README\.md/);
    assert.ok(existsSync(join(dir, host, 'skills', 'desk', '..', '..', '..', 'oikos', 'agents', 'desk', 'README.md')), 'the pointer resolves');
  }
  const check = tool(dir, 'sync', ['--check']);
  assert.equal(check.status, 0, check.output);
  assert.match(check.stdout, /1 agent\(s\)/);

  writeFileSync(join(dir, 'oikos.yaml'), readFileSync(join(dir, 'oikos.yaml'), 'utf8').replace('agents: [desk]', 'agents: []'));
  const stale = tool(dir, 'sync', ['--check']);
  assert.equal(stale.status, 1);
  assert.match(stale.stdout, /out of date: \.claude\/skills\/desk \(stale\)/);
  assert.equal(tool(dir, 'sync', []).status, 0);
  assert.ok(!existsSync(join(dir, '.claude', 'skills', 'desk')), 'an unlisted agent is not delivered');
  assert.ok(existsSync(join(dir, '.claude', 'skills', 'notes', 'SKILL.md')), 'the skills stay');
});

test('sync leaves a folder of the agent\'s name that it did not write, and says so', () => {
  const dir = installation((t) => t);
  mkdirSync(join(dir, '.claude', 'skills', 'desk'), { recursive: true });
  writeFileSync(join(dir, '.claude', 'skills', 'desk', 'SKILL.md'), '---\nname: desk\ndescription: the person\'s own\n---\n');
  const r = tool(dir, 'sync', ['--check']);
  assert.equal(r.status, 1);
  assert.match(r.stdout, /problem: \.claude\/skills\/desk: a skill of the same name that oikos did not write/);
});

test('oikos.yaml: an agent oikos does not have, a malformed agents part and a bad desk part are problems', () => {
  const check = (edit) => tool(installation(edit), 'sync', ['--check']);
  const unknown = check((t) => t.replace('agents: [desk]', 'agents: [desk, ghost]'));
  assert.equal(unknown.status, 1);
  assert.match(unknown.stdout, /problem: oikos\.yaml: agents names 'ghost', which oikos does not have \(desk\)/);
  assert.match(check((t) => t.replace('agents: [desk]', 'agents:\n  desk: yes')).stdout, /'agents' must be a list of agent names/);
  assert.match(check((t) => t.replace('warm_days: 30', 'warm_days: soon')).stdout, /desk\.warm_days: must be a whole number of days/);
  assert.match(check((t) => t.replace('cold_days: 90', 'cold_days: 20')).stdout, /desk\.cold_days \(20\) must be greater than desk\.warm_days \(30\)/);
  assert.match(check((t) => t.replace('cold_days: 90', 'cold_days: 90\n  keep: 1')).stdout, /desk\.keep: unknown key/);
});

test('landscape agents says whether this installation switches an agent on', () => {
  const on = JSON.parse(tool(installation((t) => t), 'landscape', ['agents', 'desk', '--json']).stdout)[0];
  assert.equal(on.enabled, true);
  assert.equal(on.file, 'oikos/agents/desk/README.md');
  const off = JSON.parse(tool(installation((t) => t.replace('agents: [desk]', '')), 'landscape', ['agents', '--json']).stdout)[0];
  assert.equal(off.enabled, false);
  const skill = JSON.parse(tool(installation((t) => t), 'landscape', ['skills', 'notes', '--json']).stdout)[0];
  assert.equal(skill.group, 'ongoing');
  assert.deepEqual(skill.connectors, []);
});

/** A host hook's answer, in the installation `dir`. */
function hook(dir, guard, payload, env = {}) {
  const r = spawnSync(process.execPath, [HOOK, guard], {
    cwd: dir, input: JSON.stringify(payload), encoding: 'utf8', env: cleanEnv({ CLAUDE_PROJECT_DIR: dir, ...env }),
  });
  assert.equal(r.status, 0, r.stderr);
  return r.stdout.trim() ? JSON.parse(r.stdout.trim().split('\n').pop()) : null;
}

test('the session-start hook names the agents switched on, and only those', () => {
  const context = (dir) => hook(dir, 'session-start', { hook_event_name: 'SessionStart' }).hookSpecificOutput.additionalContext;
  const on = context(installation((t) => t));
  assert.match(on, /Standing agents switched on here \(agents: in oikos\.yaml\)/);
  assert.match(on, /- desk: The standing desk for a manager's incoming material[^\n]*\(oikos\/agents\/desk\/README\.md\)/);
  assert.doesNotMatch(context(installation((t) => t.replace('agents: [desk]', ''))), /Standing agents/);
});

test('the context-pressure advice puts the desk\'s card before the park, only where the desk is on', () => {
  const advice = (dir) => {
    const transcript = join(tempDir('pressure-'), 'transcript.jsonl');
    writeFileSync(transcript, `${JSON.stringify({ type: 'assistant', message: { usage: { input_tokens: 172_000 } } })}\n`);
    return hook(dir, 'context-pressure', { session_id: `desk-${process.pid}-${dir}`, hook_event_name: 'UserPromptSubmit', transcript_path: transcript },
      { TMPDIR: tempDir('state-'), OIKOS_CONTEXT_WINDOW: '200000' }).systemMessage;
  };
  assert.match(advice(installation((t) => t)), /In a desk session do this first: write the card of the current topic and run `node oikos\/tools\/desk\/cli\.mjs index` — the desk is not parked\./);
  assert.doesNotMatch(advice(installation((t) => t.replace('agents: [desk]', ''))), /desk session/);
});

test('handoff keeps the desk\'s folder out of its packages', () => {
  const dir = installation((t) => t);
  const refused = tool(dir, 'handoff', ['park', '--name', 'desk', '--from', 'oikos.yaml']);
  assert.equal(refused.status, 1);
  assert.match(refused.output, /\.local\/desk\/ is the desk agent's folder, not a package/);
  assert.equal(tool(dir, 'handoff', ['park', '--task', 'DESK-1', '--from', 'oikos.yaml']).status, 0, 'only the name `desk` is reserved');
  mkdirSync(join(dir, '.local', 'desk'), { recursive: true });
  writeFileSync(join(dir, '.local', 'desk', 'HANDOFF.md'), '# not a package\n');
  const list = tool(dir, 'handoff', ['list']);
  assert.equal(list.status, 0, list.output);
  assert.doesNotMatch(list.stdout, /^desk /m);
});
